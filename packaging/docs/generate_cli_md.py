"""Write docs/CLI.md from the viewer binary and the Python parsers.

The committed page is compared with this output in CI, so a hand edit drifts
and the job fails.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

from voxprint_lucent.cli import build_parser

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs" / "CLI.md"


def _help(argv: list[str]) -> str:
    completed = subprocess.run(argv, check=True, capture_output=True, text=True)
    return completed.stdout.replace("\r\n", "\n").rstrip() + "\n"


def render(viewer: Path) -> str:
    """Combine the viewer, module, and tools help into one markdown page."""
    binary = _help([str(viewer), "--help"])
    module = build_parser().format_help().replace("\r\n", "\n").rstrip() + "\n"
    tools = _help([sys.executable, "-m", "voxprint_lucent.tools_host", "--help"])
    return (
        "<!-- Generated by packaging/docs/generate_cli_md.py. Do not edit by hand. -->\n"
        "\n"
        "# Command line\n"
        "\n"
        "Generated from `voxprint-lucent --help`, the Python module parser, "
        "and `voxprint-lucent-tools --help`.\n"
        "\n"
        "## Viewer\n"
        "\n"
        "The installed application is this program.\n"
        "\n"
        "```text\n"
        f"{binary}"
        "```\n"
        "\n"
        "## Python module\n"
        "\n"
        "A source checkout's `voxprint-lucent` console script uses this parser. "
        "It can also export a copy. The installed viewer is the program above.\n"
        "\n"
        "```text\n"
        f"{module}"
        "```\n"
        "\n"
        "## Tools\n"
        "\n"
        "`voxprint-lucent-tools` is the on-demand helper. The viewer starts it "
        "when you open the info panel or Enlarge.\n"
        "\n"
        "```text\n"
        f"{tools}"
        "```\n"
    )


def main(argv: list[str] | None = None) -> int:
    """Regenerate docs/CLI.md, or fail when the file does not match."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--viewer",
        type=Path,
        required=True,
        help="Path to the voxprint-lucent binary",
    )
    parser.add_argument("--check", action="store_true", help="Fail when docs/CLI.md differs")
    args = parser.parse_args(argv)
    if not args.viewer.is_file():
        print(f"viewer binary not found: {args.viewer}", file=sys.stderr)
        return 1
    text = render(args.viewer)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != text:
            print("docs/CLI.md does not match --help. Regenerate it:", file=sys.stderr)
            print(
                f"  python packaging/docs/generate_cli_md.py --viewer {args.viewer}",
                file=sys.stderr,
            )
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
